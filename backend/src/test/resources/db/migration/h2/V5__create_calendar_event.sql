CREATE TABLE woorisai.calendar_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    author_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    start_at TIMESTAMP WITH TIME ZONE NOT NULL,
    end_at TIMESTAMP WITH TIME ZONE NOT NULL,
    all_day BOOLEAN NOT NULL,
    note VARCHAR(2000),
    kind VARCHAR(4) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    deleted_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT calendar_event_pk PRIMARY KEY (id),
    CONSTRAINT calendar_event_author_fk FOREIGN KEY (author_id)
        REFERENCES woorisai.participant (id) ON DELETE RESTRICT,
    CONSTRAINT calendar_event_title_ck CHECK (char_length(trim(title)) > 0),
    CONSTRAINT calendar_event_interval_ck CHECK (end_at > start_at),
    CONSTRAINT calendar_event_kind_ck CHECK (kind IN ('MINE', 'OURS')),
    CONSTRAINT calendar_event_timestamps_ck CHECK (updated_at >= created_at
        AND (deleted_at IS NULL OR deleted_at >= created_at))
);
CREATE INDEX calendar_event_range_idx ON woorisai.calendar_event (start_at, end_at, id);
